#!/usr/bin/env python3
"""
Render the scoring rubric deliverable from rubric.json.

PS-01 deliverable 02 asks for a one-page rubric listing the risk weights and
combination rules. Writing that by hand guarantees it drifts from the code the
first time a weight changes, so it is generated from the same file the engine
loads: scoring/src/main/resources/rubric.json.

Outputs:
    docs/SCORING_RUBRIC.md        full reference
    docs/SCORING_RUBRIC.pdf       the one-page deliverable

The PDF step needs reportlab (pip install reportlab). Without it the Markdown
is still written and the script exits 0 with a warning, so the build never
fails just because a PDF library is missing.

Usage:
    python3 tools/render_rubric.py [--check]

    --check  verify the PDF really is one page and fail if not.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
RUBRIC = REPO / "scoring" / "src" / "main" / "resources" / "rubric.json"
MD_OUT = REPO / "docs" / "SCORING_RUBRIC.md"
PDF_OUT = REPO / "docs" / "SCORING_RUBRIC.pdf"


def pretty(name: str) -> str:
    return name.replace("_", " ").capitalize()


def load() -> dict:
    if not RUBRIC.exists():
        sys.exit(f"error: {RUBRIC} not found")
    return json.loads(RUBRIC.read_text(encoding="utf-8"))


def band_ranges(bands: dict) -> list[tuple[str, str]]:
    m, h, c = bands["medium_from"], bands["high_from"], bands["critical_from"]
    return [
        ("Low", f"0-{m - 1}"),
        ("Medium", f"{m}-{h - 1}"),
        ("High", f"{h}-{c - 1}"),
        ("Critical", f"{c}-100"),
    ]


def render_markdown(r: dict) -> str:
    out: list[str] = []
    w = out.append

    w("# Scoring rubric")
    w("")
    w(f"Generated from `scoring/src/main/resources/rubric.json` (version {r['version']}) "
      f"by `tools/render_rubric.py`. **Do not edit this file by hand** — edit the JSON "
      f"and re-run the script. The risk engine loads the same file, so the numbers below "
      f"are the numbers actually used.")
    w("")

    w("## Bands")
    w("")
    w("| Band | Score |")
    w("|---|---|")
    for name, rng in band_ranges(r["bands"]):
        w(f"| {name} | {rng} |")
    w("")

    w("## How a score is built")
    w("")
    w("```")
    w("score = min(sum of permission categories, permission_subtotal_cap)")
    w("      + min(sum of special access,        special_access_cap)")
    w("      + provenance modifiers")
    w("      + static manifest findings")
    w("      + threat-intelligence modifier")
    w("      + combination-rule bonuses")
    w("      + context-mismatch bonus")
    w("      then x system-app dampening, clamped to 0..100")
    w("```")
    w("")
    caps = r["caps"]
    w(f"The **permission subtotal cap of {caps['permission_subtotal']:.0f}** is the most "
      f"important number here. Ordinary permissions, however many an app holds, cannot by "
      f"themselves push it past Medium. Reaching High or Critical requires special access, "
      f"a combination rule, poor provenance, a context mismatch or a threat-intelligence "
      f"hit. Without that cap a legitimate messaging app outscores a torch app holding an "
      f"accessibility service, and the ranking stops answering \"which app can do the most "
      f"harm?\".")
    w("")
    w(f"Other ceilings: special access {caps['special_access_subtotal']:.0f}, "
      f"network category {caps['network_category']:.0f} "
      f"(network is low risk alone and earns its weight through combinations).")
    w("")

    w("## Permission category weights")
    w("")
    w("`points = category_base x permission_sensitivity x protection_multiplier x state_multiplier`, "
      "with each additional permission in the same category discounted by the diminishing "
      "factor, then capped.")
    w("")
    w("| Category | Base | Cap | Diminishing |")
    w("|---|---:|---:|---:|")
    for cat, vals in r["category_weights"].items():
        if vals["base"] == 0:
            continue
        w(f"| {pretty(cat)} | {vals['base']:.0f} | {vals['cap']:.0f} | {vals['diminishing']:.2f} |")
    w("")

    w("### Multipliers")
    w("")
    w("| Protection level | Multiplier |")
    w("|---|---:|")
    for k, v in r["protection_multipliers"].items():
        w(f"| {pretty(k)} | {v:.2f} |")
    w("")
    sm = r["state_multipliers"]
    w("| Grant state | Multiplier |")
    w("|---|---:|")
    w(f"| Granted | {sm['granted']:.2f} |")
    w(f"| Declared, not granted | {sm['declared_not_granted']:.2f} |")
    w(f"| Cannot be granted | {sm['not_grantable']:.2f} |")
    w("")

    w("## Special access weights")
    w("")
    w("Scored from the detected access state, never from the permission list, so one "
      "capability is never counted twice.")
    w("")
    w("| Access | Enabled | Declared only |")
    w("|---|---:|---:|")
    for kind, vals in sorted(
        r["special_access_weights"].items(), key=lambda kv: -kv[1]["enabled"]
    ):
        w(f"| {pretty(kind)} | {vals['enabled']:.0f} | {vals['declared_only']:.0f} |")
    w("")

    w("## Combination rules")
    w("")
    w("Predicates live in `scoring/.../CombinationRules.kt` and are joined to these numbers "
      "by id. A rule with a band floor forces at least that band regardless of the "
      "arithmetic, and the score is lifted to the bottom of that band so the number and the "
      "word never contradict each other.")
    w("")
    w("| Rule | Bonus | Band floor | What it means |")
    w("|---|---:|---|---|")
    for rule_id, cfg in sorted(
        r["combination_rules"].items(), key=lambda kv: -kv[1]["bonus"]
    ):
        floor = cfg.get("band_floor") or "-"
        w(f"| `{rule_id}` | +{cfg['bonus']} | {floor} | {cfg['headline']} |")
    w("")

    w("## Provenance modifiers")
    w("")
    w("| Signal | Points |")
    w("|---|---:|")
    prov = r["provenance"]
    labels = {
        "sideloaded": "Installed from outside an app store",
        "adb_or_none": "No install source recorded",
        "unknown_installer": "Installer not recognised",
        "google_play": "Installed from Google Play",
        "oem_store": "Installed from an OEM store",
        "target_sdk_below_23": "Built for Android below 6.0 (no runtime permissions)",
        "no_launcher_icon": "No icon in the app list",
        "installed_within_hours": "Installed very recently",
    }
    for key, label in labels.items():
        w(f"| {label} | {prov[key]:+d} |")
    w(f"| (recent-install window) | {prov['recent_install_window_hours']} hours |")
    w("")

    w("## Static manifest findings")
    w("")
    w("| Finding | Points |")
    w("|---|---:|")
    man = r["manifest"]
    man_labels = {
        "debuggable": "Shipped in developer mode",
        "cleartext_traffic": "Permits unencrypted network traffic",
        "test_only": "Marked as a test build",
        "unguarded_exported_provider": "Exported data provider with no permission guard (each)",
        "unguarded_exported_component": "Other exported component with no guard (each)",
    }
    for key, label in man_labels.items():
        w(f"| {label} | +{man[key]} |")
    w(f"| (ceiling on exported-component points) | {man['max_unguarded_component_points']} |")
    w("")

    w("## Reducers")
    w("")
    w("| Reducer | Multiplier |")
    w("|---|---:|")
    red = r["reducers"]
    red_labels = {
        "verified_security_tool_device_admin": "Verified security/MDM tool holding device admin",
        "verified_accessibility_tool": "Verified accessibility tool",
        "role_holder_category": "Category explained by a device role (default SMS app, dialer...)",
        "system_app_dampening": "System or updated-system app (whole score)",
    }
    for key, label in red_labels.items():
        w(f"| {label} | x{red[key]:.2f} |")
    w("")
    w("A reducer applies only on **verified** trust: a matching package name alone never "
      "qualifies, because package names are trivially spoofable. Trust requires a pinned "
      "signing certificate or arrival from Google Play or an OEM store.")
    w("")

    w("## Threat intelligence")
    w("")
    ti = r["threat_intel"]
    w(f"- Malicious verdict: **+{ti['malicious']}** and a band floor of "
      f"**{ti['malicious_band_floor']}**")
    w(f"- Suspicious verdict: **+{ti['suspicious']}**")
    w("")
    w("Lookups send a SHA-256 fingerprint and nothing else, only after explicit, "
      "revocable, default-off consent.")
    w("")

    w("## Context mismatch")
    w("")
    w("| Severity | Bonus | Band floor |")
    w("|---|---:|---|")
    for sev, bonus in r["context_mismatch_bonus"].items():
        floor = r["context_mismatch_band_floor"].get(sev) or "-"
        w(f"| {pretty(sev)} | +{bonus} | {floor} |")
    w("")
    w("Only the single worst mismatch scores. Several mismatches on one app describe the "
      "same underlying oddity, and adding them up would count one observation repeatedly.")
    w("")

    w("## Explanations")
    w("")
    w(f"Every High or Critical app carries at least "
      f"**{r['minimum_reasons_for_high_or_critical']} plain-language reasons**, ranked by "
      f"contribution. Reasons are emitted by the scoring rules themselves, never written in "
      f"a second pass, so the number and the words cannot drift apart. Padding, when needed, "
      f"only ever promotes things that are true about that app; nothing is invented.")
    w("")

    return "\n".join(out) + "\n"


def render_pdf(r: dict) -> bool:
    """One-page PDF. Returns False if reportlab is unavailable."""
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle
        from reportlab.lib.units import mm
        from reportlab.pdfgen import canvas as pdfcanvas
    except ImportError:
        return False

    PDF_OUT.parent.mkdir(parents=True, exist_ok=True)
    c = pdfcanvas.Canvas(str(PDF_OUT), pagesize=A4)
    width, height = A4

    left = 14 * mm
    right = width - 14 * mm
    y = height - 14 * mm

    def text(s, size=6.6, bold=False, dy=3.3 * mm, x=left, color=colors.black):
        nonlocal y
        c.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        c.setFillColor(color)
        c.drawString(x, y, s)
        y -= dy

    def heading(s):
        nonlocal y
        y -= 1.2 * mm
        text(s, size=8, bold=True, dy=4.0 * mm)

    # Title
    c.setFont("Helvetica-Bold", 13)
    c.drawString(left, y, "App Risk Auditor — Scoring Rubric")
    y -= 5.5 * mm
    c.setFont("Helvetica", 6.4)
    c.setFillColor(colors.grey)
    c.drawString(left, y, f"PS-01 deliverable 02 · generated from rubric.json v{r['version']} "
                          f"by tools/render_rubric.py · do not edit by hand")
    y -= 5 * mm
    c.setFillColor(colors.black)
    c.setLineWidth(0.4)
    c.line(left, y, right, y)
    y -= 4.5 * mm

    # Bands + formula side by side
    heading("Bands")
    bands = " · ".join(f"{n} {rng}" for n, rng in band_ranges(r["bands"]))
    text(bands, size=7)

    heading("Score construction")
    caps = r["caps"]
    text("min(permission categories, %d) + min(special access, %d) + provenance + manifest "
         "+ threat intel + combinations + context mismatch"
         % (caps["permission_subtotal"], caps["special_access_subtotal"]), size=6.4)
    text("then x system-app dampening, clamped 0-100. Network category capped at %d."
         % caps["network_category"], size=6.4)
    text("The permission cap is load-bearing: permissions alone can never exceed Medium.",
         size=6.4, bold=True)

    # Two columns: categories and special access.
    # Helvetica is proportional, so columns are placed at explicit x positions
    # rather than padded with spaces — space-padding only aligns in a monospace
    # font and produces a visibly ragged table here.
    col2 = left + 92 * mm
    heading("Permission categories (base / cap / diminishing)")
    y_cats = y

    def row(x_label, label, values, value_xs, size=6.2):
        nonlocal y
        c.setFont("Helvetica", size)
        c.drawString(x_label, y, label)
        for value, vx in zip(values, value_xs):
            c.drawRightString(vx, y, value)
        y -= 2.9 * mm

    cat_value_xs = [left + 58 * mm, left + 70 * mm, left + 84 * mm]
    for cat, v in r["category_weights"].items():
        if v["base"] == 0:
            continue
        row(left, pretty(cat), [f"{v['base']:.0f}", f"{v['cap']:.0f}", f"{v['diminishing']:.2f}"],
            cat_value_xs)

    y_after_cats = y
    y = y_cats
    c.setFont("Helvetica-Bold", 7)
    c.drawString(col2, y + 4.0 * mm, "Special access (enabled / declared only)")
    sa_value_xs = [col2 + 56 * mm, col2 + 70 * mm]
    for kind, v in sorted(r["special_access_weights"].items(), key=lambda kv: -kv[1]["enabled"]):
        row(col2, pretty(kind), [f"{v['enabled']:.0f}", f"{v['declared_only']:.0f}"], sa_value_xs)

    y = min(y, y_after_cats) - 1.5 * mm

    # Multipliers row
    heading("Multipliers")
    prot = " · ".join(f"{pretty(k)} x{v:.2f}" for k, v in r["protection_multipliers"].items())
    sm = r["state_multipliers"]
    text(f"Protection: {prot}", size=6.2, dy=2.9 * mm)
    text(f"State: granted x{sm['granted']:.2f} · declared-not-granted "
         f"x{sm['declared_not_granted']:.2f} · not grantable x{sm['not_grantable']:.2f}",
         size=6.2, dy=2.9 * mm)

    # Combination rules
    heading("Combination rules (predicate ids match CombinationRules.kt)")
    for rule_id, cfg in sorted(r["combination_rules"].items(), key=lambda kv: -kv[1]["bonus"]):
        floor = cfg.get("band_floor")
        c.setFont("Helvetica", 5.9)
        c.drawString(left, y, f"+{cfg['bonus']}")
        c.drawString(left + 8 * mm, y, rule_id)
        c.drawString(left + 72 * mm, y, f"floor {floor}" if floor else "")
        c.drawString(left + 88 * mm, y, cfg["headline"])
        y -= 2.75 * mm

    # Modifiers
    heading("Provenance, manifest, intel, context, reducers")
    prov = r["provenance"]
    text(f"Provenance: sideloaded {prov['sideloaded']:+d} · no install record {prov['adb_or_none']:+d} "
         f"· unknown installer {prov['unknown_installer']:+d} · Google Play {prov['google_play']:+d} "
         f"· OEM store {prov['oem_store']:+d} · targetSdk<23 {prov['target_sdk_below_23']:+d} "
         f"· no launcher icon {prov['no_launcher_icon']:+d} · new install {prov['installed_within_hours']:+d}",
         size=6.0, dy=2.9 * mm)
    man = r["manifest"]
    text(f"Manifest: debuggable +{man['debuggable']} · cleartext +{man['cleartext_traffic']} "
         f"· test-only +{man['test_only']} · unguarded provider +{man['unguarded_exported_provider']} ea "
         f"· other exported +{man['unguarded_exported_component']} ea (max {man['max_unguarded_component_points']})",
         size=6.0, dy=2.9 * mm)
    ti = r["threat_intel"]
    text(f"Threat intel: malicious +{ti['malicious']} and floor {ti['malicious_band_floor']} "
         f"· suspicious +{ti['suspicious']} · hash only, explicit opt-in, default off",
         size=6.0, dy=2.9 * mm)
    ctx = " · ".join(
        f"{pretty(s)} +{b}" + (f" floor {r['context_mismatch_band_floor'][s]}"
                               if r["context_mismatch_band_floor"].get(s) else "")
        for s, b in r["context_mismatch_bonus"].items() if b
    )
    text(f"Context mismatch: {ctx} · only the worst mismatch scores", size=6.0, dy=2.9 * mm)
    red = r["reducers"]
    text(f"Reducers: verified MDM device admin x{red['verified_security_tool_device_admin']:.2f} "
         f"· verified accessibility tool x{red['verified_accessibility_tool']:.2f} "
         f"· role holder category x{red['role_holder_category']:.2f} "
         f"· system app x{red['system_app_dampening']:.2f} "
         f"(verified = pinned certificate or trusted store; a name match alone is never trusted)",
         size=6.0, dy=2.9 * mm)

    y -= 1.5 * mm
    c.setLineWidth(0.4)
    c.line(left, y, right, y)
    y -= 3.5 * mm
    text(f"Every High or Critical app carries at least {r['minimum_reasons_for_high_or_critical']} "
         f"plain-language reasons, ranked by contribution and emitted by the scoring rules "
         f"themselves — never written in a separate pass.", size=6.4, bold=True)

    c.showPage()
    c.save()
    return True


def page_count(path: pathlib.Path) -> int:
    data = path.read_bytes()
    return data.count(b"/Type /Page") - data.count(b"/Type /Pages")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the PDF is not exactly one page")
    args = ap.parse_args()

    r = load()

    MD_OUT.parent.mkdir(parents=True, exist_ok=True)
    MD_OUT.write_text(render_markdown(r), encoding="utf-8")
    print(f"wrote {MD_OUT.relative_to(REPO)}")

    if render_pdf(r):
        pages = page_count(PDF_OUT)
        print(f"wrote {PDF_OUT.relative_to(REPO)} ({pages} page{'s' if pages != 1 else ''})")
        if pages != 1:
            msg = f"rubric PDF is {pages} pages; PS-01 asks for one"
            if args.check:
                print(f"error: {msg}", file=sys.stderr)
                return 1
            print(f"warning: {msg}", file=sys.stderr)
    else:
        print("warning: reportlab not installed, PDF not generated "
              "(pip install reportlab)", file=sys.stderr)
        if args.check:
            return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
